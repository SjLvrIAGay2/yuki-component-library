#!/usr/bin/env node
/**
 * Generates the two aggregation points that must never be edited by hand:
 *
 *   packages/ui/src/index.ts          public barrel
 *   packages/ui/src/styles/index.css  ordered stylesheet entry
 *
 * Component folders are discovered from the filesystem, so parallel authors
 * only ever add files inside their own `components/<name>/` folder.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const uiRoot = join(root, 'packages', 'ui');
const componentsDir = join(uiRoot, 'src', 'components');

const BANNER = `// AUTO-GENERATED by scripts/generate.mjs — do not edit by hand.\n// Run \`npm run gen\` after adding or removing a component folder.\n`;

async function listComponents() {
  const entries = await readdir(componentsDir, { withFileTypes: true });
  const names = [];
  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name.startsWith('_') || entry.name.startsWith('.')) continue;
    if (existsSync(join(componentsDir, entry.name, 'index.ts'))) names.push(entry.name);
  }
  names.sort();
  return names;
}

async function main() {
  const names = await listComponents();
  const barrel = [
    BANNER,
    `import './styles/index.css';`,
    '',
    ...names.map((name) => `export * from './components/${name}';`),
    '',
    `export * from './theme';`,
    `export * from './locale';`,
    `export * from './hooks';`,
    `export * from './animation';`,
    '',
  ].join('\n');

  await writeFile(join(uiRoot, 'src', 'index.ts'), barrel, 'utf8');

  const cssHeader = `/* AUTO-GENERATED by scripts/generate.mjs — do not edit by hand. */\n`;
  const imports = [`@import './tokens.css';`, `@import './base.css';`, `@import '../animation/Animation.css';`];

  // Keep the cascade stable: foundations first, layout second, then the other families.
  const basic = ['button', 'divider', 'icon', 'link', 'typography'];
  const layout = ['aspect-ratio', 'container', 'flex', 'grid', 'space', 'splitter'];
  const first = new Set([...basic, ...layout]);
  const ordered = [...basic, ...layout].filter(name => names.includes(name))
    .concat(names.filter(name => !first.has(name)));
  for (const name of ordered) {
    const files = (await readdir(join(componentsDir, name)))
      .filter((file) => file.endsWith('.css'))
      .sort();
    for (const file of files) {
      imports.push(`@import '../components/${name}/${file}';`);
    }
  }

  const cssContent = `${cssHeader}${imports.join('\n')}\n`;
  await writeFile(join(uiRoot, 'src', 'styles', 'index.css'), cssContent, 'utf8');

  const tokenCss = await readFile(join(uiRoot, 'src', 'styles', 'tokens.css'), 'utf8');
  const tokenMatch = [...tokenCss.matchAll(/(--yuki-[a-z0-9-]+)\s*:/g)].map((match) => match[1]);
  const tokenNames = [...new Set(tokenMatch)].sort();
  const tokenCount = tokenNames.length;

  // Expose build-time facts to the docs site without shipping a bundler plugin.
  const docsGenerated = join(root, 'apps', 'docs', 'src', 'generated', 'stats.ts');
  const stats = `// AUTO-GENERATED by scripts/generate.mjs — do not edit by hand.
export const componentNames = ${JSON.stringify(names, null, 2)} as const;
export const componentCount = ${names.length};
export const dependencyCount = ${Object.keys(JSON.parse(await readFile(join(uiRoot, 'package.json'), 'utf8')).dependencies).length};
export const tokenNames = ${JSON.stringify(tokenNames, null, 2)} as const;
export const tokenCount = ${tokenCount};
`;
  await writeFile(docsGenerated, stats, 'utf8');

  console.log(
    `generated barrel with ${names.length} components and ${imports.length - 3} component stylesheets (${tokenCount} token declarations)`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
